static void oled_set_pos(u8 x, u8 y)
{
	ssd1306_spi_write_byte(0xb0+y,COMMAND);
	ssd1306_spi_write_byte(((x&0xf0)>>4)|0x10,COMMAND);
	ssd1306_spi_write_byte((x&0x0f)|0x01,COMMAND);
}

static void oled_drawBmp(u8 x0, u8 y0,u8 x1, u8 y1,u8 BMP[])
{
 int j=0;
 int x,y;

  if(y1%8==0) y=y1/8;
  else y=y1/8+1;
	for(y=y0;y<y1;y++)
	{
		oled_set_pos(x0,y);
    	for(x=x0;x<x1;x++)
			ssd1306_spi_write_byte(BMP[j++],DATA);
	}
}

