#include "ssd1306.h"
#include <hal_gpio.h>

typedef enum {
    SPI_MASTER_OK = 0,
    SPI_MASTER_INVALID_PARAMETER = -1,
    SPI_MASTER_ERROR_BUSY = -2,
    SPI_MASTER_ERROR_TIMEOUT = -3,
    SPI_MASTER_ERROR = -4
} spi_master_status_t;

typedef enum {
    SPI_MASTER_PORT_0 = 0,
    SPI_MASTER_PORT_1 = 1,
    SPI_MASTER_PORT_2 = 2,
    SPI_MASTER_PORT_3 = 3,
    SPI_MASTER_PORT_4 = 4,
    SPI_MASTER_PORT_5 = 5
} hal_spi_master_port_t;

extern spi_master_status_t hal_spi_write(hal_spi_master_port_t port, void *buf, uint32_t size);

/* SSD1306 SPI 端口定义 */
#define SSD1306_SPI_PORT   SPI_MASTER_PORT_1
#define COMMAND 0
#define DATA    1
#define HIGH 	1
#define LOW 	0

#define RES_LEVEL(val) 	sunxi_lcd_gpio_set_value(0, 1,val)
#define DC_LEVEL(val) 	sunxi_lcd_gpio_set_value(0,0, val)
#define CS_LEVEL(val) 	sunxi_lcd_gpio_set_value(0, 4, val)
#define MOSI_LEVEL(val) sunxi_lcd_gpio_set_value(0, 2, val)
#define SCL_LEVEL(val) 	sunxi_lcd_gpio_set_value(0, 3, val)

