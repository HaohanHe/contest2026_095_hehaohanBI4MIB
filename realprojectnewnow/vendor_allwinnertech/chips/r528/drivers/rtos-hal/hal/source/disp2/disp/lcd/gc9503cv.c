static void lcd_panel_init(u32 sel)
{
	__u32 i;
	syslog(LOG_DEBUG, "lcd_panel_init\n");
	sunxi_lcd_dsi_clk_enable(sel);
	for (i = 0;; i++) {
		if (lcm_gc9503cv_setting[i].count == REGFLAG_END_OF_TABLE)
			break;
		else if (lcm_gc9503cv_setting[i].count == REGFLAG_DELAY) {
			sunxi_lcd_delay_ms(lcm_gc9503cv_setting[i].para_list[0]);
		} else {
			dsi_dcs_wr(sel, lcm_gc9503cv_setting[i].cmd,
				   lcm_gc9503cv_setting[i].para_list,
				   lcm_gc9503cv_setting[i].count);
		}
	}
}

static void lcd_panel_exit(u32 sel)
{
	__u32 i;
	for (i = 0;; i++) {
		if (lcm_gc9503cv_sleep_setting[i].count == REGFLAG_END_OF_TABLE)
			break;
		else if (lcm_gc9503cv_sleep_setting[i].count == REGFLAG_DELAY) {
			sunxi_lcd_delay_ms(lcm_gc9503cv_sleep_setting[i].para_list[0]);
		} else {
			dsi_dcs_wr(sel, lcm_gc9503cv_sleep_setting[i].cmd,
				   lcm_gc9503cv_sleep_setting[i].para_list,
				   lcm_gc9503cv_sleep_setting[i].count);
		}
	}
}

